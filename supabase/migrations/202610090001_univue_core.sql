create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists (
    select 1 from public.staff_profiles
    where user_id = auth.uid() and active
  );
$$;

create or replace function public.inventory_overview(p_product_code text)
returns table (size text, quantity integer, status text)
language sql
stable
security definer
set search_path = public
as $$
  select i.size,
         i.quantity,
         case when i.quantity = 0 then 'OUT_OF_STOCK'
              when i.quantity <= 3 then 'LOW_STOCK'
              else 'AVAILABLE' end as status
  from public.inventory i
  join public.products p on p.code = i.product_code and p.active
  where i.product_code = p_product_code
  order by array_position(array['XS','S','M','L','XL','XXL'], i.size);
$$;

create or replace function public.check_inventory(p_product_code text, p_size text)
returns table (product_code text, size text, quantity integer, status text)
language sql
stable
security definer
set search_path = public
as $$
  select i.product_code,
         i.size,
         i.quantity,
         case when i.quantity = 0 then 'OUT_OF_STOCK'
              when i.quantity <= 3 then 'LOW_STOCK'
              else 'AVAILABLE' end as status
  from public.inventory i
  join public.products p on p.code = i.product_code and p.active
  where i.product_code = p_product_code and i.size = upper(p_size)
  limit 1;
$$;

create or replace function public.record_inquiry(
  p_kiosk_code text,
  p_product_code text,
  p_size text,
  p_response_ms integer default null
)
returns table (product_code text, size text, quantity integer, status text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kiosk_id uuid;
  v_quantity integer;
  v_status text;
begin
  select id into v_kiosk_id from public.kiosks where code = p_kiosk_code and active;
  select c.quantity, c.status into v_quantity, v_status
  from public.check_inventory(p_product_code, p_size) c;

  insert into public.inquiry_logs(kiosk_id, product_code, size, available_quantity, stock_status, success, response_ms)
  values (v_kiosk_id, p_product_code, upper(p_size), v_quantity, v_status, v_quantity is not null, p_response_ms);

  return query select p_product_code, upper(p_size), v_quantity, v_status;
end;
$$;

create or replace function public.place_order(
  p_kiosk_code text,
  p_customer jsonb,
  p_items jsonb,
  p_fulfillment text,
  p_payment_method text,
  p_notes text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kiosk_id uuid;
  v_order_id uuid;
  v_reference text;
  v_item jsonb;
  v_product public.products%rowtype;
  v_code text;
  v_size text;
  v_quantity integer;
  v_total numeric(10, 2) := 0;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 20 then
    raise exception 'INVALID_ITEMS';
  end if;
  if p_fulfillment not in ('PICKUP', 'CAMPUS_DELIVERY') then raise exception 'INVALID_FULFILLMENT'; end if;
  if p_payment_method not in ('CASH', 'GCASH') then raise exception 'INVALID_PAYMENT_METHOD'; end if;
  if nullif(trim(p_customer->>'customerName'), '') is null
    or nullif(trim(p_customer->>'studentId'), '') is null
    or nullif(trim(p_customer->>'collegeDepartment'), '') is null
    or nullif(trim(p_customer->>'contactNumber'), '') is null then
    raise exception 'MISSING_CUSTOMER_DETAILS';
  end if;

  select id into v_kiosk_id from public.kiosks where code = p_kiosk_code and active;
  if v_kiosk_id is null then raise exception 'UNKNOWN_KIOSK'; end if;

  v_reference := 'UNIVUE-' || to_char(clock_timestamp(), 'YYMMDD') || '-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
  insert into public.orders(reference, kiosk_id, customer_name, student_id, college_department, contact_number, fulfillment, notes, payment_method)
  values (
    v_reference, v_kiosk_id,
    left(trim(p_customer->>'customerName'), 120),
    left(trim(p_customer->>'studentId'), 60),
    left(trim(p_customer->>'collegeDepartment'), 120),
    left(trim(p_customer->>'contactNumber'), 40),
    p_fulfillment,
    left(coalesce(p_notes, ''), 500),
    p_payment_method
  ) returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_code := v_item->>'item';
    v_size := upper(v_item->>'size');
    begin
      v_quantity := (v_item->>'quantity')::integer;
    exception when others then
      raise exception 'INVALID_QUANTITY';
    end;
    if v_quantity < 1 or v_quantity > 30 or v_size not in ('XS','S','M','L','XL','XXL') then
      raise exception 'INVALID_ORDER_ITEM';
    end if;

    select * into v_product from public.products where code = v_code and active;
    if not found then raise exception 'UNKNOWN_PRODUCT:%', v_code; end if;

    update public.inventory
    set quantity = quantity - v_quantity, updated_at = now()
    where product_code = v_code and size = v_size and quantity >= v_quantity;
    if not found then raise exception 'INSUFFICIENT_STOCK:%:%', v_code, v_size; end if;

    insert into public.order_items(order_id, product_code, size, quantity, unit_price)
    values (v_order_id, v_code, v_size, v_quantity, v_product.price);
    v_total := v_total + (v_product.price * v_quantity);
  end loop;

  update public.orders set subtotal = v_total, total = v_total where id = v_order_id;
  insert into public.payments(order_id, method, amount) values (v_order_id, p_payment_method, v_total);

  return jsonb_build_object(
    'id', v_order_id,
    'reference', v_reference,
    'total', v_total,
    'status', 'AWAITING_PAYMENT',
    'paymentStatus', 'PENDING'
  );
end;
$$;

create or replace function public.request_assistance(
  p_kiosk_code text,
  p_product_code text default null,
  p_size text default null,
  p_order_reference text default null,
  p_message text default 'Student requested staff assistance.'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kiosk_id uuid;
  v_request public.assistance_requests%rowtype;
begin
  select id into v_kiosk_id from public.kiosks where code = p_kiosk_code and active;
  if v_kiosk_id is null then raise exception 'UNKNOWN_KIOSK'; end if;
  if p_size is not null and upper(p_size) not in ('XS','S','M','L','XL','XXL') then raise exception 'UNKNOWN_SIZE'; end if;

  insert into public.assistance_requests(kiosk_id, product_code, size, order_reference, message)
  values (v_kiosk_id, p_product_code, upper(p_size), p_order_reference, left(coalesce(p_message, 'Student requested staff assistance.'), 300))
  returning * into v_request;

  return jsonb_build_object(
    'id', v_request.id,
    'accessToken', v_request.access_token,
    'status', v_request.status,
    'requestedAt', v_request.requested_at
  );
end;
$$;

create or replace function public.assistance_status(p_request_id uuid, p_access_token uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id', id,
    'status', status,
    'requestedAt', requested_at,
    'acknowledgedAt', acknowledged_at,
    'resolvedAt', resolved_at
  )
  from public.assistance_requests
  where id = p_request_id and access_token = p_access_token;
$$;

