-- UNIVUE core database
-- Safe public access is exposed through read policies and SECURITY DEFINER RPCs.

create extension if not exists pgcrypto;

create table public.products (
  code text primary key,
  name text not null,
  category text not null check (category in ('FORMAL', 'T_SHIRT', 'PE_UNIFORM')),
  gender text check (gender in ('MALE', 'FEMALE') or gender is null),
  price numeric(10, 2) not null check (price >= 0),
  image_path text not null,
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.kiosks (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  display_name text not null,
  location text not null default '',
  active boolean not null default true,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.staff_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'STAFF' check (role in ('STAFF', 'ADMIN')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.inventory (
  product_code text not null references public.products(code) on update cascade on delete restrict,
  size text not null check (size in ('XS', 'S', 'M', 'L', 'XL', 'XXL')),
  quantity integer not null default 0 check (quantity between 0 and 30),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null,
  primary key (product_code, size)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  kiosk_id uuid references public.kiosks(id) on delete set null,
  customer_name text not null,
  student_id text not null,
  college_department text not null,
  contact_number text not null,
  fulfillment text not null check (fulfillment in ('PICKUP', 'CAMPUS_DELIVERY')),
  notes text not null default '',
  payment_method text not null check (payment_method in ('CASH', 'GCASH')),
  subtotal numeric(10, 2) not null default 0 check (subtotal >= 0),
  total numeric(10, 2) not null default 0 check (total >= 0),
  status text not null default 'AWAITING_PAYMENT' check (status in ('AWAITING_PAYMENT', 'PAID', 'PREPARING', 'READY', 'COMPLETED', 'CANCELLED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_code text not null references public.products(code) on update cascade on delete restrict,
  size text not null check (size in ('XS', 'S', 'M', 'L', 'XL', 'XXL')),
  quantity integer not null check (quantity between 1 and 30),
  unit_price numeric(10, 2) not null check (unit_price >= 0),
  line_total numeric(10, 2) generated always as (quantity * unit_price) stored
);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null unique references public.orders(id) on delete cascade,
  method text not null check (method in ('CASH', 'GCASH')),
  amount numeric(10, 2) not null check (amount >= 0),
  status text not null default 'PENDING' check (status in ('PENDING', 'CONFIRMED', 'FAILED', 'CANCELLED')),
  provider_reference text,
  confirmed_at timestamptz,
  confirmed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.receipts (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null unique references public.orders(id) on delete cascade,
  receipt_number text not null unique,
  printed_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.assistance_requests (
  id uuid primary key default gen_random_uuid(),
  access_token uuid not null default gen_random_uuid(),
  kiosk_id uuid references public.kiosks(id) on delete set null,
  product_code text references public.products(code) on update cascade on delete set null,
  size text check (size in ('XS', 'S', 'M', 'L', 'XL', 'XXL') or size is null),
  order_reference text,
  message text not null default 'Student requested staff assistance.',
  status text not null default 'PENDING' check (status in ('PENDING', 'ACKNOWLEDGED', 'RESOLVED', 'CANCELLED')),
  requested_at timestamptz not null default now(),
  acknowledged_at timestamptz,
  resolved_at timestamptz,
  handled_by uuid references auth.users(id) on delete set null
);

create table public.inquiry_logs (
  id bigint generated by default as identity primary key,
  kiosk_id uuid references public.kiosks(id) on delete set null,
  product_code text references public.products(code) on update cascade on delete set null,
  size text check (size in ('XS', 'S', 'M', 'L', 'XL', 'XXL') or size is null),
  available_quantity integer check (available_quantity between 0 and 30),
  stock_status text check (stock_status in ('AVAILABLE', 'LOW_STOCK', 'OUT_OF_STOCK') or stock_status is null),
  success boolean not null default true,
  response_ms integer check (response_ms >= 0),
  queried_at timestamptz not null default now()
);

create index orders_created_at_idx on public.orders (created_at desc);
create index orders_status_idx on public.orders (status, created_at desc);
create index assistance_requests_status_idx on public.assistance_requests (status, requested_at desc);
create index inquiry_logs_queried_at_idx on public.inquiry_logs (queried_at desc);

